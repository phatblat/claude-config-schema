// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * Derives a PascalCase type name from a schema filename.
 *
 * Examples:
 *   settings.json       → Settings
 *   plugin-manifest.json → PluginManifest
 *   skill-frontmatter.json → SkillFrontmatter
 */
function deriveTypeName(filename: string): string {
  const base = filename.replace(/\.json$/, "");
  return base
    .split("-")
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join("");
}

/**
 * Collects schema entries from upstream/ (top-level .json only) and
 * authored/ (.json files, excluding _meta/).
 */
function collectSchemas(): Array<{ name: string; schema: string }> {
  const schemas: Array<{ name: string; schema: string }> = [];

  // Upstream: top-level .json files only
  if (existsSync(UPSTREAM_DIR)) {
    const entries = readdirSync(UPSTREAM_DIR, { withFileTypes: true });
    for (const entry of entries) {
      if (entry.isFile() && entry.name.endsWith(".json")) {
        const filePath = join(UPSTREAM_DIR, entry.name);
        const typeName = deriveTypeName(entry.name);
        schemas.push({
          name: typeName,
          schema: readFileSync(filePath, "utf-8"),
        });
      }
    }
  }

  // Authored: .json files recursively, excluding _meta/
  if (existsSync(AUTHORED_DIR)) {
    collectAuthoredSchemas(AUTHORED_DIR, schemas);
  }

  return schemas;
}

function collectAuthoredSchemas(
  dir: string,
  schemas: Array<{ name: string; schema: string }>
): void {
  const entries = readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      // Skip the _meta directory
      if (entry.name === "_meta") continue;
      collectAuthoredSchemas(fullPath, schemas);
    } else if (entry.isFile() && entry.name.endsWith(".json")) {
      const typeName = deriveTypeName(entry.name);
      schemas.push({
        name: typeName,
        schema: readFileSync(fullPath, "utf-8"),
      });
    }
  }
}

/**
 * Ensures the parent directory for a file path exists.
 */
function ensureParentDir(filePath: string): void {
  mkdirSync(dirname(filePath), { recursive: true });
}

// ---------------------------------------------------------------------------
// Generation
// ---------------------------------------------------------------------------

interface GenerationResult {
  lang: string;
  outputPath: string;
  typeCount: number;
}

async function generateForLanguage(
  target: LanguageTarget,
  schemas: ReadonlyArray<{ name: string; schema: string }>
): Promise<GenerationResult> {
  const outputFile = join(GENERATED_DIR, target.outputPath);
  const outputDir = dirname(outputFile);

  // Create the output directory if it doesn't exist
  mkdirSync(outputDir, { recursive: true });

  const schemaInput = new JSONSchemaInput(new FetchingJSONSchemaStore());

  for (const { name, schema } of schemas) {
    await schemaInput.addSource({ name, schema });
  }

  const inputData = new InputData();
  inputData.addInput(schemaInput);

  const result = await quicktype({
    inputData,
    lang: target.lang,
    rendererOptions: target.rendererOptions,
  });

  const content =
    target.commentHeader + "\n\n" + result.lines.join("\n") + "\n";

  ensureParentDir(outputFile);
  writeFileSync(outputFile, content);

  if (target.scaffoldFiles) {
    for (const sf of target.scaffoldFiles) {
      const sfPath = join(GENERATED_DIR, sf.path);
      ensureParentDir(sfPath);
      writeFileSync(sfPath, sf.content);
    }
  }

  return {
    lang: target.lang,
    outputPath: target.outputPath,
    typeCount: schemas.length,
  };
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main(): Promise<void> {
  const schemas = collectSchemas();

  if (schemas.length === 0) {
    console.log("No schema files found in upstream/ or authored/.");
    console.log("Run 'npm run sync-upstream' first to fetch upstream schemas.");
    process.exit(0);
  }

  console.log(`Found ${schemas.length} schema(s):`);
  for (const s of schemas) {
    console.log(`  - ${s.name}`);
  }
  console.log();

  const results: GenerationResult[] = [];

  for (const target of LANGUAGES) {
    const result = await generateForLanguage(target, schemas);
    results.push(result);
  }

  console.log("--- generate-bindings summary ---\n");
  for (const r of results) {
    console.log(
      `  GENERATED  ${r.lang.padEnd(12)} → ${r.outputPath}  (${r.typeCount} type(s))`
    );
  }
  console.log(`\n${results.length} language(s) generated.`);
}

main().catch((error: unknown) => {
  console.error(
    "generate-bindings failed:",
    error instanceof Error ? error.message : error
  );
  process.exit(1);
});
