/**
 * Generates typed language bindings from JSON Schema files.
 *
 * Collects schemas from:
 *   - `upstream/` (top-level .json files only)
 *   - `authored/` (.json files, excluding `_meta/`)
 *
 * For each target language (Go, TypeScript, Python, Rust), runs quicktype-core
 * to produce typed code and writes the output to `generated/<lang>/`.
 *
 * Languages whose output directory does not exist are silently skipped.
 */

